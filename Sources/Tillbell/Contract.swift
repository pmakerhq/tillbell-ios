import Foundation

// Messages of the Tillbell bridge contract, the specification of this library:
// https://github.com/pmakerhq/tillbell-rails/blob/main/docs/bridge-contract.md
//
// The contract was written for Google Play first; README.md explains how each field maps to
// StoreKit 2. Replies are checked against the contract's JSON Schemas in the unit tests. Their
// schemas forbid unknown fields, so optional fields are left out when nil (the synthesized
// Encodable does that); fields the schema requires even when null, like basePlanId, are encoded
// explicitly.

/// A plan shown by the paywall. On the App Store, [productId] is the App Store product
/// identifier and [basePlanId] must be null: each subscription duration is its own product.
struct Plan: Codable, Equatable {
    let productId: String
    var basePlanId: String?
}

/// `products` request: the plans whose price the paywall shows.
struct ProductsRequest: Decodable {
    let products: [Plan]
}

/// Result of `products` and `restore`.
enum QueryResult: String, Encodable {
    case ok, unavailable, error
}

/// A plan known to the App Store, with the price formatted for the customer's storefront.
struct PricedPlan: Encodable, Equatable {
    let productId: String
    let basePlanId: String?
    let formattedPrice: String

    private enum CodingKeys: String, CodingKey { case productId, basePlanId, formattedPrice }

    func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
        try container.encode(productId, forKey: .productId)
        try container.encode(basePlanId, forKey: .basePlanId) // Required, even when null.
        try container.encode(formattedPrice, forKey: .formattedPrice)
    }
}

/// `products` reply. `products` is set when `result` is ok, `message` may detail a failure.
struct ProductsReply: Encodable, Equatable {
    let result: QueryResult
    var products: [PricedPlan]?
    var message: String?
}

/// Google Play replacement mode of a plan change. The App Store decides how a plan change
/// takes effect from the subscription group levels, so it is validated and otherwise ignored.
enum ReplacementMode: String, Decodable {
    case WITH_TIME_PRORATION, CHARGE_PRORATED_PRICE, WITHOUT_PRORATION, CHARGE_FULL_PRICE, DEFERRED
}

/// `purchase` request. `obfuscatedAccountId` is the UUID generated by the server, passed to
/// StoreKit unchanged as the `appAccountToken`. `oldPurchaseToken` and `replacementMode` come
/// together, for a plan change.
struct PurchaseRequest: Decodable {
    let productId: String
    var basePlanId: String?
    let obfuscatedAccountId: String
    var oldPurchaseToken: String?
    var replacementMode: ReplacementMode?
}

/// Result of `purchase`.
enum PurchaseResult: String, Encodable {
    case purchased, pending, canceled
    case alreadyOwned = "already_owned"
    case unavailable, error
}

/// `purchase` reply. `productId` and `purchaseToken` are set for purchased; pending has a
/// `productId` and no token, StoreKit gives none until the purchase is approved.
struct PurchaseReply: Encodable, Equatable {
    let result: PurchaseResult
    var productId: String?
    var purchaseToken: String?
    var message: String?
}

/// A subscription the App Store account is entitled to.
struct OwnedPurchase: Encodable, Equatable {
    let productId: String
    let purchaseToken: String
}

/// `restore` reply. `purchases` is set (possibly empty) when `result` is ok.
struct RestoreReply: Encodable, Equatable {
    let result: QueryResult
    var purchases: [OwnedPurchase]?
    var message: String?
}
